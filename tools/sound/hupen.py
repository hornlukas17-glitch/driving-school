"""
Hupen fürs Spiel (komplett selbst erzeugt, keine Aufnahmen).

  python3 tools/sound/hupen.py   ->  dist/sound/DS_Hupe_<Name>.wav (+ Vorschau-MP3) und src/Hupen.lua

Die Asset-IDs nach dem Hochladen in Studio kommen in tools/sound/ids.json (Schlüssel = Dateiname ohne .wav),
dann dieses Skript nochmal laufen lassen. Ohne ID zeigt das Spiel nur die "HONK!"-Blase über dem Auto.
"""
import json, math, os, subprocess
import numpy as np
import scipy.signal as sg

SR = 44100
WURZEL = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
AUS = os.path.join(WURZEL, "dist", "sound")
VORSCHAU = os.path.join(AUS, "vorschau")
IDS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ids.json")


def zeit(dauer):
    return np.arange(int(SR * dauer)) / SR


def huelle(n, an=0.01, ab=0.06):
    h = np.ones(n)
    a, b = int(SR * an), int(SR * ab)
    h[:a] = np.linspace(0, 1, a)
    h[-b:] = np.linspace(1, 0, b)
    return h


def saege(phase):
    return 2 * (phase / (2 * math.pi) % 1) - 1


def ton(freq_kurve, obertoene=(1, 0.5, 0.33, 0.25, 0.2)):
    """freq_kurve: Frequenz je Sample -> sägezahnähnlicher Ton (Summe von Obertönen)"""
    phase = 2 * math.pi * np.cumsum(freq_kurve) / SR
    return sum(g * np.sin(k * phase) for k, g in enumerate(obertoene, start=1))


def formant(x, f, q):
    w = 2 * math.pi * f / SR
    al = math.sin(w) / (2 * q)
    b = [al, 0, -al]
    a = [1 + al, -2 * math.cos(w), 1 - al]
    return sg.lfilter(b, a, x)


def normal():
    # klassische Zweiklang-Autohupe (Terz)
    t = zeit(0.7)
    x = ton(np.full(len(t), 420.0)) + ton(np.full(len(t), 525.0))
    x = formant(x, 900, 1.2) * 3 + x * 0.3
    return np.tanh(x * 1.5) * huelle(len(t))


def clown():
    # Ballhupe: "honk honk" mit leichtem Absacken der Tonhöhe
    stuecke = []
    for d in (0.22, 0.32):
        t = zeit(d)
        f = 330 - 40 * t / d
        x = ton(f, (1, 0.8, 0.6, 0.45, 0.3, 0.2))
        x = formant(x, 1200, 2) * 4
        stuecke += [np.tanh(x * 2) * huelle(len(t), 0.005, 0.04), np.zeros(int(SR * 0.08))]
    return np.concatenate(stuecke)


def ente():
    # "Quak quak": nasaler Ton mit schneller Tonhöhen-Kurve
    stuecke = []
    for _ in range(2):
        t = zeit(0.24)
        f = 520 + 180 * np.sin(np.pi * t / 0.24) - 150 * t / 0.24
        x = ton(f, (1, 0.9, 0.8, 0.6, 0.5, 0.4, 0.3))
        x = formant(x, 1400, 3) * 3 + formant(x, 2600, 4) * 2
        stuecke += [np.tanh(x * 2.5) * huelle(len(t), 0.004, 0.05), np.zeros(int(SR * 0.07))]
    return np.concatenate(stuecke)


def lufthorn():
    # Lufthorn: tiefer Akkord mit leichtem Vibrato, lang
    t = zeit(1.3)
    vib = 1 + 0.006 * np.sin(2 * math.pi * 5.5 * t)
    x = sum(ton(np.full(len(t), f) * vib) for f in (185.0, 233.0, 277.0))
    x = formant(x, 700, 1) * 2 + x * 0.4
    return np.tanh(x * 1.2) * huelle(len(t), 0.03, 0.15)


def melodie():
    # eigene kurze Tusch-Melodie (frei erfunden): ta-ta-ta-TAAA
    stuecke = []
    for f, d in ((523, 0.12), (523, 0.12), (659, 0.12), (784, 0.45)):
        t = zeit(d)
        x = ton(np.full(len(t), float(f)), (1, 0.0, 0.33, 0.0, 0.2))  # rechteckähnlich (ungerade Obertöne)
        stuecke += [np.tanh(x * 1.5) * huelle(len(t), 0.005, 0.03), np.zeros(int(SR * 0.03))]
    return np.concatenate(stuecke)


# Schlüssel = Name im Spiel, Text = Blase über dem Auto, Pass = nötiger Gamepass (None = für alle)
HUPEN = [
    ("normal", "Classic", "📯 HONK!", None, normal),
    ("clown", "Clown horn", "🤡 HONK HONK!", "hupen", clown),
    ("ente", "Duck", "🦆 QUACK QUACK!", "hupen", ente),
    ("lufthorn", "Air horn", "📢 BWAAAAH!", "hupen", lufthorn),
    ("melodie", "Fanfare", "🎺 TA-TA-TA-TAAA!", "hupen", melodie),
]


def schreiben(name, x):
    os.makedirs(AUS, exist_ok=True)
    x = x / (np.max(np.abs(x)) + 1e-9) * 0.9
    daten = (x * 32767).astype(np.int16)
    pfad = os.path.join(AUS, name + ".wav")
    import wave
    with wave.open(pfad, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(daten.tobytes())
    try:
        os.makedirs(VORSCHAU, exist_ok=True)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", pfad, os.path.join(VORSCHAU, name + ".mp3")], check=False)
    except FileNotFoundError:
        pass
    return pfad


def main():
    ids = json.load(open(IDS)) if os.path.exists(IDS) else {}
    zeilen = ["-- Generated by tools/sound/hupen.py – do not edit by hand.",
              "-- Horn sounds (own synthesis). id = 0: not uploaded yet, the game only shows the HONK bubble.",
              "return {"]
    for key, name, text, pass_, f in HUPEN:
        datei = "DS_Hupe_" + key[0].upper() + key[1:]
        schreiben(datei, f())
        zeilen.append('\t{ key = "%s", name = "%s", text = "%s", pass = %s, id = %d },'
                      % (key, name, text, ('"%s"' % pass_) if pass_ else "nil", int(ids.get(datei, 0))))
    zeilen.append("}")
    open(os.path.join(WURZEL, "src", "Hupen.lua"), "w").write("\n".join(zeilen) + "\n")
    print("Hupen:", ", ".join(h[0] for h in HUPEN))


if __name__ == "__main__":
    main()
