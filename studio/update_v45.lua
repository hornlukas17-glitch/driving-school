	local namen = {}
	for _, sp in lobby.spieler do table.insert(namen, sp.DisplayName) end
	anTeilnehmer(lobby.spieler, { typ = "party", phase = "beitritt", titel = ("🏁 %d/%d IN THE PARTY"):format(#lobby.spieler, Party.MAX),
